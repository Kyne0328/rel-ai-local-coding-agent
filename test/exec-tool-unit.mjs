import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'relai-exec-tool-'));
const workspace = path.join(temp, 'workspace');
const nested = path.join(workspace, 'nested');
const stateDir = path.join(temp, 'state');
const configPath = path.join(temp, 'config.json');
const previousConfig = process.env.REL_AI_MCP_CONFIG;
const gitExecutable = process.platform === 'win32'
  ? String.raw`C:\Program Files\Git\cmd\git.exe`
  : '/usr/bin/git';

function git(args) {
  return execFileSync(gitExecutable, args, { cwd: workspace, stdio: 'pipe' });
}

function quote(value) {
  const text = String(value);
  if (process.platform === 'win32') return `'${text.replaceAll("'", "''")}'`;
  return `'${text.replaceAll("'", `'"'"'`)}'`;
}

function nodeCommand(script, ...args) {
  const pieces = [quote(process.execPath), quote(script), ...args.map(quote)];
  return process.platform === 'win32' ? `& ${pieces.join(' ')}` : pieces.join(' ');
}

fs.mkdirSync(nested, { recursive: true });
fs.mkdirSync(path.join(workspace, 'scripts'), { recursive: true });
fs.mkdirSync(path.join(workspace, 'src'), { recursive: true });
fs.writeFileSync(path.join(workspace, 'src', 'index.js'), 'module.exports = true;\n');
fs.writeFileSync(path.join(workspace, 'scripts', 'emit.js'), [
  "process.stdout.write(`cwd=${require('node:path').basename(process.cwd())};env=${process.env.RELAI_EXEC_TEST};relai=${process.env.REL_AI_MCP}`);",
  "process.stderr.write('warning-stream');"
].join('\n'));
fs.writeFileSync(path.join(workspace, 'scripts', 'fail.js'), "process.stderr.write('expected failure'); process.exit(7);\n");
fs.writeFileSync(path.join(workspace, 'scripts', 'large.js'), "process.stdout.write('x'.repeat(20000));\n");
fs.writeFileSync(path.join(workspace, 'scripts', 'hang.js'), "setInterval(() => {}, 1000);\n");
fs.writeFileSync(path.join(workspace, 'scripts', 'mutate.js'), "require('node:fs').writeFileSync(process.argv[2], 'generated by exec\\n');\n");
fs.writeFileSync(path.join(workspace, 'package.json'), JSON.stringify({
  scripts: { check: 'node --check src/index.js' }
}, null, 2));

git(['init']);
git(['config', 'user.email', 'relai@example.test']);
git(['config', 'user.name', 'RelAI Exec Test']);
git(['add', '.']);
git(['commit', '-m', 'initial']);

fs.writeFileSync(configPath, JSON.stringify({
  version: 2,
  stateDir,
  auditLogPath: path.join(stateDir, 'audit.jsonl'),
  maxOutputBytes: 2097152,
  patch: { backup: false, requireCleanGit: false, maxUpdateBytes: 2097152 },
  workspaces: {
    app: {
      path: workspace,
      commands: {},
      testCommands: { check: 'npm run check' }
    }
  }
}, null, 2));
process.env.REL_AI_MCP_CONFIG = configPath;

try {
  const { callTool, getToolSchemas } = require('../src/tools.js');
  const { readConfig } = require('../src/config.js');
  const { readAudit } = require('../src/audit.js');
  const sessionCache = require('../src/sessionCache.js');
  const { resetToolActivity } = require('../src/toolActivity.js');

  const schema = getToolSchemas().find(tool => tool.name === 'relai_exec');
  assert.ok(schema, 'relai_exec must be connector-visible');
  assert.ok(schema.inputSchema.properties.command, 'connector schema must retain command');
  assert.ok(schema.inputSchema.properties.cwd, 'connector schema must expose cwd');

  const secret = 'exec-secret-value';
  const context = { publicHttpOnly: true, taskScopeId: 'exec-main' };
  const success = await callTool('relai_exec', {
    workspace: 'app',
    command: `${nodeCommand(path.join(workspace, 'scripts', 'emit.js'))} --token ${secret}`,
    env: { RELAI_EXEC_TEST: 'visible', API_TOKEN: secret }
  }, context);
  assert.equal(success.ok, true);
  assert.equal(success.exitCode, 0);
  assert.match(success.stdout, /cwd=workspace;env=visible;relai=1/);
  assert.equal(success.stderr, 'warning-stream');
  assert.ok(success.durationMs >= 0);
  assert.ok(success.stdoutBytes > 0);
  assert.ok(success.stderrBytes > 0);
  assert.deepEqual(success.environmentKeys, ['API_TOKEN', 'RELAI_EXEC_TEST']);
  assert.equal(Object.hasOwn(success, 'commandSummary'), false, 'connector response must not duplicate the audit-only summary');

  const auditText = JSON.stringify(readAudit(readConfig(), { limit: 100 }).entries);
  assert.doesNotMatch(auditText, new RegExp(secret));
  assert.match(auditText, /\[REDACTED\]|\[redacted\]/);
  assert.match(auditText, /RELAI_EXEC_TEST/);

  sessionCache.setCachedRead('app', path.join(workspace, 'src', 'index.js'), 1, 'cached');
  assert.equal(sessionCache.cacheStats().entries, 1);
  await callTool('relai_exec', {
    workspace: 'app',
    command: nodeCommand(path.join(workspace, 'scripts', 'emit.js'))
  }, context);
  assert.equal(sessionCache.cacheStats().entries, 0, 'every command must invalidate the workspace read cache');

  const nestedResult = await callTool('relai_exec', {
    workspace: 'app',
    command: nodeCommand(path.join(workspace, 'scripts', 'emit.js')),
    cwd: 'nested',
    env: { RELAI_EXEC_TEST: 'nested' }
  }, context);
  assert.equal(nestedResult.cwd, 'nested');
  assert.match(nestedResult.stdout, /cwd=nested;env=nested/);

  const failure = await callTool('relai_exec', {
    workspace: 'app',
    command: nodeCommand(path.join(workspace, 'scripts', 'fail.js'))
  }, context);
  assert.equal(failure.ok, false);
  assert.equal(failure.exitCode, 7);
  assert.match(failure.stderr, /expected failure/);

  await assert.rejects(
    () => callTool('relai_exec', { workspace: 'app', command: 'echo invalid', cwd: '..' }, context),
    /escapes the workspace/i
  );
  await assert.rejects(
    () => callTool('relai_exec', { workspace: 'app', command: 'echo invalid', env: { INVALID: 1 } }, context),
    /must be a string/i
  );

  const large = await callTool('relai_exec', {
    workspace: 'app',
    command: nodeCommand(path.join(workspace, 'scripts', 'large.js')),
    maxOutputBytes: 1000
  }, context);
  assert.equal(large.ok, true);
  assert.equal(large.stdoutTruncated, true);
  assert.equal(large.stdoutBytes, 20000);
  assert.match(large.stdout, /truncated output/);
  assert.ok(Buffer.byteLength(large.stdout, 'utf8') <= 1000);

  const timedOut = await callTool('relai_exec', {
    workspace: 'app',
    command: nodeCommand(path.join(workspace, 'scripts', 'hang.js')),
    timeoutMs: 1000
  }, context);
  assert.equal(timedOut.ok, false);
  assert.equal(timedOut.timedOut, true);
  assert.match(timedOut.error, /Timed out after 1000ms/);

  const mutation = await callTool('relai_exec', {
    workspace: 'app',
    command: nodeCommand(path.join(workspace, 'scripts', 'mutate.js'), 'generated.txt')
  }, context);
  assert.equal(mutation.ok, true);
  assert.deepEqual(mutation.changedFiles, ['generated.txt']);
  assert.equal(mutation.mutationTracking, 'git');
  fs.rmSync(path.join(workspace, 'generated.txt'));

  resetToolActivity();
  const noValidationContext = { publicHttpOnly: true, taskScopeId: 'exec-no-validation' };
  const noValidationTask = await callTool('relai_start_task', { workspace: 'app' }, noValidationContext);
  await callTool('relai_exec', {
    workspace: 'app',
    task_id: noValidationTask.task_id,
    command: nodeCommand(path.join(workspace, 'scripts', 'emit.js'))
  }, noValidationContext);
  const readOnlyExecCompletion = await callTool('relai_complete_task', {
    workspace: 'app',
    task_id: noValidationTask.task_id,
    summary: 'Read-only command task completed without validation.'
  }, noValidationContext);
  assert.equal(readOnlyExecCompletion.ok, true);
  assert.equal(readOnlyExecCompletion.validationStatus, 'not_required');

  resetToolActivity();
  const validatedContext = { publicHttpOnly: true, taskScopeId: 'exec-after-validation-readonly' };
  const validatedTask = await callTool('relai_start_task', { workspace: 'app' }, validatedContext);
  await callTool('relai_run_checks', { workspace: 'app', task_id: validatedTask.task_id, level: 'standard' }, validatedContext);
  await callTool('relai_exec', {
    workspace: 'app',
    task_id: validatedTask.task_id,
    command: nodeCommand(path.join(workspace, 'scripts', 'emit.js'))
  }, validatedContext);
  const completion = await callTool('relai_complete_task', {
    workspace: 'app',
    task_id: validatedTask.task_id,
    summary: 'Read-only command followed the passed validation.'
  }, validatedContext);
  assert.equal(completion.ok, true);

  resetToolActivity();
  const mutationContext = { publicHttpOnly: true, taskScopeId: 'exec-after-validation-mutation' };
  const mutationTask = await callTool('relai_start_task', { workspace: 'app' }, mutationContext);
  await callTool('relai_run_checks', { workspace: 'app', task_id: mutationTask.task_id, level: 'standard' }, mutationContext);
  await callTool('relai_exec', {
    workspace: 'app',
    task_id: mutationTask.task_id,
    command: nodeCommand(path.join(workspace, 'scripts', 'mutate.js'), 'after-validation.txt')
  }, mutationContext);
  await assert.rejects(
    () => callTool('relai_complete_task', {
      workspace: 'app',
      task_id: mutationTask.task_id,
      summary: 'Mutation after validation must be rejected.'
    }, mutationContext),
    /code changed after the last passed validation/i
  );

  console.log('relai_exec unit and integration tests passed.');
} finally {
  if (previousConfig == null) delete process.env.REL_AI_MCP_CONFIG;
  else process.env.REL_AI_MCP_CONFIG = previousConfig;
  fs.rmSync(temp, { recursive: true, force: true });
}
